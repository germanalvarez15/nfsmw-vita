def name_hash(name):
    """bFileGetFilenameHash: uppercase, '/' -> '\\', then a DJB-style hash seeded with ~0."""
    h = 0xFFFFFFFF
    for ch in name.upper().replace("/", "\\").encode("latin-1"):
        h = ((h << 5) + h + ch) & 0xFFFFFFFF
    return h


def find(folder, *parts):
    """Path of a file or folder, matching the names case-insensitively."""
    path = folder
    for part in parts:
        wanted = part.upper()
        match = next((e for e in os.listdir(path) if e.upper() == wanted), None)
        if match is None:
            return None
        path = os.path.join(path, match)
    return path


def read_directory(disc):
    zdir = find(disc, "NFS", "ZDIR.BIN")
    if zdir is None:
        sys.exit("NFS/ZDIR.BIN not found in %s" % disc)
    with open(zdir, "rb") as f:
        data = f.read()
    entries = {}
    for off in range(0, len(data) - ENTRY.size + 1, ENTRY.size):
        hash_, file_number, local_sector, _, size, _ = ENTRY.unpack_from(data, off)
        entries[hash_] = (file_number, local_sector, size)
    return entries


def copy_entry(disc, entry, out_path):
    file_number, local_sector, size = entry
    source = find(disc, "NFS", "ZZDATA%d.BIN" % file_number)
    if source is None:
        sys.exit("NFS/ZZDATA%d.BIN not found in %s" % (file_number, disc))
    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    with open(source, "rb") as src, open(out_path, "wb") as dst:
        src.seek(local_sector * SECTOR)
        remaining = size
        while remaining:
            chunk = src.read(min(remaining, CHUNK))
            if not chunk:
                raise IOError("%s: the disc ended early" % out_path)
            dst.write(chunk)
            remaining -= len(chunk)


def convert_movie(disc, entry, name, out):
    """Writes MOVIES/<NAME>.MP4 from the disc's MOVIES\\<name>.mpc (same settings as tools/convert_movies.sh)."""
    base = name.split("\\")[-1].rsplit(".", 1)[0].upper()
    dst = os.path.join(out, "MOVIES", base + ".MP4")
    with tempfile.TemporaryDirectory() as tmp:
        src = os.path.join(tmp, "movie.mpc")
        copy_entry(disc, entry, src)
        partial = os.path.join(tmp, "movie.mp4")
        # 512x416 like the source; H.264 Main 3.1 and AAC-LC 48 kHz are what the Vita decodes in hardware.
        subprocess.run(
            ["ffmpeg", "-v", "error", "-y", "-i", src,
             "-c:v", "libx264", "-profile:v", "main", "-level", "3.1", "-pix_fmt", "yuv420p", "-preset", "slow",
             "-crf", "20", "-maxrate", "2500k", "-bufsize", "5000k",
             "-c:a", "aac", "-b:a", "160k", "-ar", "48000", "-ac", "2",
             "-movflags", "+faststart", partial],
            check=True)
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        shutil.move(partial, dst)


def main():
    args = [a for a in sys.argv[1:] if a != "--no-movies"]
    with_movies = "--no-movies" not in sys.argv
    if len(args) != 2:
        sys.exit(__doc__)
    disc, out = args
    if find(disc, "SYSTEM.CNF") is None:
        sys.exit("SYSTEM.CNF not found: %s is not the root of a PS2 disc" % disc)
    with open(find(disc, "SYSTEM.CNF"), "rb") as f:
        if b"SLUS_213.51" not in f.read():
            sys.exit("This is not Need for Speed: Most Wanted Black Edition (SLUS-21351)")

    if with_movies and shutil.which("ffmpeg") is None:
        print("ffmpeg was not found: the movies are skipped. Install ffmpeg and run this again.")
        with_movies = False

    entries = read_directory(disc)
    copied = skipped = missing = movies = failed = 0
    for name in FILES:
        entry = entries.get(name_hash(name))
        if entry is None:
            missing += 1
            continue
        is_movie = name.upper().endswith(".MPC")
        if is_movie:
            if not with_movies:
                continue
            base = name.split("\\")[-1].rsplit(".", 1)[0].upper()
            if os.path.exists(os.path.join(out, "MOVIES", base + ".MP4")):
                skipped += 1
                continue
            try:
                convert_movie(disc, entry, name, out)
                movies += 1
            except subprocess.CalledProcessError:
                failed += 1
                print("could not convert %s" % name)
            continue
        dst = os.path.join(out, *name.split("\\"))
        if os.path.exists(dst) and os.path.getsize(dst) == entry[2]:
            skipped += 1
            continue
        copy_entry(disc, entry, dst)
        copied += 1
        if copied % 100 == 0:
            print("%d files copied..." % copied)
    print("Copied %d files and converted %d movies to %s (%d already there)" % (copied, movies, out, skipped))
    if missing:
        print("%d listed files are not on this disc and were skipped" % missing)
    if failed:
        print("%d movies failed: run the script again to retry them" % failed)


if __name__ == "__main__":
    main()
